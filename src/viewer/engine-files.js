// The page cannot read files, so the knowledge data and the registry go into one data module (generated, never edited by hand).
// Knowledge files are read from src/knowledge/ and the registry from src/agents/registry.json, the one place the order is written.
export function teamDataSource(srcDir = SRC_DIR) {
  const knowledge = {};
  for (const rel of listKnowledgeFiles(srcDir)) knowledge[rel] = JSON.parse(readFileSync(join(srcDir, 'knowledge', rel), 'utf8'));
  const registry = JSON.parse(readFileSync(join(srcDir, 'agents', 'registry.json'), 'utf8'));
  const lines = Object.keys(knowledge).map((rel) => `  ${JSON.stringify(rel)}: ${JSON.stringify(knowledge[rel])},`);
  return [
    '// Generated by npm run export-engine from src/knowledge/ and src/agents/registry.json. Do not edit by hand.',
    '// The page cannot read files, so the design team gets its knowledge files and its registry from here.',
    'export const knowledge = {',
    ...lines,
    '};',
    `export const registryData = ${JSON.stringify(registry)};`,
    '',
  ].join('\n');
}

// Copy the team's files and write the data module. Returns the relative paths written (data.js included).
export function copyTeam(srcDir = SRC_DIR, outDir = TEAM_DIR) {
  const files = listTeamFiles();
  for (const rel of files) {
    const target = join(outDir, rel);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(join(srcDir, rel), target);
  }
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'data.js'), teamDataSource(srcDir));
  return [...files, 'data.js'];
}
